// Connect to MongoDB
async function addAreas() {
    try {
        console.log('Connecting to MongoDB...');
        await mongoose.connect(dbConfig.url, {
            useNewUrlParser: true,
            useUnifiedTopology: true
        });
        console.log('✓ Connected to MongoDB successfully\n');

        // Remove duplicates from the list itself (case-insensitive, trimmed)
        const seen = new Set();
        const uniqueAreas = [];
        const listDuplicates = [];

        console.log(`Removing duplicates from the list...`);
        for (const area of areasList) {
            const trimmedArea = area.trim();
            const normalizedArea = trimmedArea.toLowerCase();
            
            if (trimmedArea === '') {
                continue; // Skip empty strings
            }
            
            if (seen.has(normalizedArea)) {
                listDuplicates.push(trimmedArea);
            } else {
                seen.add(normalizedArea);
                uniqueAreas.push(trimmedArea);
            }
        }

        if (listDuplicates.length > 0) {
            console.log(`⚠ Found ${listDuplicates.length} duplicate(s) in the list itself:`);
            listDuplicates.forEach(dup => console.log(`   - ${dup}`));
            console.log('');
        }

        console.log(`Original list: ${areasList.length} areas`);
        console.log(`After removing duplicates: ${uniqueAreas.length} unique areas\n`);

        const results = {
            success: [],
            duplicates: [],
            failed: []
        };

        console.log(`Starting to add ${uniqueAreas.length} areas...\n`);

        // Process each area
        for (let i = 0; i < uniqueAreas.length; i++) {
            const areaName = uniqueAreas[i];
            
            try {
                // Check if area already exists
                const existingArea = await Area.findOne({
                    name: areaName,
                    deleteFlag: false
                });

                if (existingArea) {
                    results.duplicates.push(areaName);
                    console.log(`[${i + 1}/${uniqueAreas.length}] ⚠ Duplicate (already in DB): ${areaName}`);
                    continue;
                }

                // Create new area
                const newArea = await Area.create({
                    name: areaName,
                    city: '',
                    state: '',
                    pinCode: '',
                    isActive: true,
                    deleteFlag: false
                });

                results.success.push(areaName);
                console.log(`[${i + 1}/${uniqueAreas.length}] ✓ Added: ${areaName}`);
            } catch (error) {
                results.failed.push({
                    name: areaName,
                    error: error.message
                });
                console.log(`[${i + 1}/${uniqueAreas.length}] ✗ Failed: ${areaName} - ${error.message}`);
            }
        }

        // Print summary
        console.log('\n' + '='.repeat(60));
        console.log('SUMMARY');
        console.log('='.repeat(60));
        console.log(`Original List: ${areasList.length} areas`);
        console.log(`After List Deduplication: ${uniqueAreas.length} unique areas`);
        if (listDuplicates.length > 0) {
            console.log(`⚠ Duplicates Removed from List: ${listDuplicates.length}`);
        }
        console.log(`✓ Successfully Added: ${results.success.length}`);
        console.log(`⚠ Duplicates (already in DB): ${results.duplicates.length}`);
        console.log(`✗ Failed: ${results.failed.length}`);

        if (results.duplicates.length > 0) {
            console.log('\nDuplicates:');
            results.duplicates.forEach(name => console.log(`  - ${name}`));
        }

        if (results.failed.length > 0) {
            console.log('\nFailed:');
            results.failed.forEach(item => console.log(`  - ${item.name}: ${item.error}`));
        }

        console.log('\n✓ Process completed!');
        
    } catch (error) {
        console.error('Error:', error.message);
        process.exit(1);
    } finally {
        // Close database connection
        await mongoose.connection.close();
        console.log('\nDatabase connection closed.');
        process.exit(0);
    }
}

